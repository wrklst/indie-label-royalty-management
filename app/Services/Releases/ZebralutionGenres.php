    /**
     * The code of a genre given by its name, in any casing, or by the
     * code itself. Null when Zebralution has no such genre.
     */
    public static function code(?string $genre): ?string
    {
        $genre = mb_strtolower(trim((string) $genre));

        if (isset(self::CODES[$genre])) {
            return $genre;
        }

        foreach (self::CODES as $code => $name) {
            if (mb_strtolower($name) === $genre) {
                return (string) $code;
            }
        }

        return null;
    }

    /**
     * Every genre name once, for suggesting while typing.
     *
     * @return list<string>
     */
    public static function names(): array
    {
        return array_values(array_unique(self::CODES));
    }
